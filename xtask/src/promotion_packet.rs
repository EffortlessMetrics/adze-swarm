pub fn render_markdown(packet: &PromotionPacket) -> String {
    let mut out = String::new();
    out.push_str(&format!("# {} Promotion Packet\n\n", packet.version));
    out.push_str("> **This packet does NOT authorize promotion or publication.**\n");
    out.push_str("> It is evidence assembly only. Promotion and crates.io publication\n");
    out.push_str("> require separate explicit decisions under #325.\n\n");
    out.push_str(&format!(
        "Machine-readable twin: `promotion-packet-{}.json` (generated from the same typed packet; do not hand-edit either file).\n\n",
        packet.version
    ));
    out.push_str(&format!(
        "**Candidate status:** {}\n\n",
        packet.candidate_status
    ));
    out.push_str("## Identity\n\n");
    out.push_str("| Field | Value |\n|---|---|\n");
    out.push_str(&format!("| Version | {} |\n", packet.version));
    out.push_str(&format!(
        "| Selected candidate commit | `{}` |\n",
        packet.selected_candidate.commit
    ));
    out.push_str(&format!(
        "| Selected candidate tree | `{}` |\n",
        packet.selected_candidate.tree
    ));
    out.push_str(&format!("| Packet commit | `{}` |\n", packet.packet_commit));
    out.push_str(&format!(
        "| Public target commit | `{}` |\n",
        packet.public_target.commit
    ));
    out.push_str(&format!(
        "| Public target tree | `{}` |\n",
        packet.public_target.tree
    ));
    out.push_str(&format!(
        "| Cargo.lock SHA-256 | `{}` |\n",
        packet.cargo_lock_sha256
    ));
    out.push_str(&format!(
        "| Roadmap counts | {} |\n\n",
        packet.roadmap_counts.status
    ));
    out.push_str("## Release graph\n\n");
    out.push_str("Publish in this exact order (from `policy/release-graph.toml`):\n\n");
    for entry in &packet.release_graph {
        out.push_str(&format!(
            "{}. `{}` {}\n",
            entry.order, entry.name, entry.version
        ));
    }
    out.push_str("\n## Receipts\n\n");
    if packet.receipts.is_empty() {
        out.push_str("No receipts attached.\n\n");
    } else {
        out.push_str("| Name | Command | Exit code | Executed counts | Source commit | Timestamp (UTC) | Artifact |\n");
        out.push_str("|---|---|---|---|---|---|---|\n");
        for r in &packet.receipts {
            out.push_str(&format!(
                "| {} | `{}` | {} | {} | `{}` | {} | {} |\n",
                r.name,
                r.command,
                r.exit_code,
                r.executed_counts,
                r.source_commit,
                r.timestamp_utc,
                r.artifact
            ));
        }
        out.push('\n');
    }
    out.push_str("## Explicit non-claims\n\n");
    for claim in &packet.non_claims {
        out.push_str(&format!("- {claim}\n"));
    }
    out.push_str("\n## Regeneration\n\n");
    out.push_str("Packet commit above records the generation base (HEAD at generation time) as provenance only. `--check` compares all generated fields and files byte-wise except the Packet commit line in this Markdown and the corresponding JSON field; every other difference is a failure.\n\n");
    let receipt_args = packet
        .receipt_files
        .iter()
        .map(|f| format!(" --receipt {f}"))
        .collect::<String>();
    out.push_str("```bash\n");
    out.push_str(&format!(
        "cargo run -q -p xtask -- promotion-packet --source {} --public-target {} --version {} --output docs/release{}\n",
        packet.selected_candidate.commit, packet.public_target.commit, packet.version, receipt_args
    ));
    out.push_str(&format!(
        "cargo run -q -p xtask -- promotion-packet --source {} --public-target {} --version {} --check{}\n",
        packet.selected_candidate.commit, packet.public_target.commit, packet.version, receipt_args
    ));
    out.push_str("```\n");
    out
}

/// Minimal SHA-256 (avoids a new dependency for one lockfile hash).
pub fn sha256_hex(data: &[u8]) -> String {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4,
        0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe,
        0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f,
        0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7,
        0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc,
        0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
        0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116,
        0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7,
        0xc67178f2,
    ];
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
        0x5be0cd19,
    ];
    let bit_len = (data.len() as u64).wrapping_mul(8);
    let mut msg = data.to_vec();
    msg.push(0x80);
    while msg.len() % 64 != 56 {
        msg.push(0);
    }
    msg.extend_from_slice(&bit_len.to_be_bytes());
    for chunk in msg.chunks_exact(64) {
        let mut w = [0u32; 64];
        for i in 0..16 {
            w[i] = u32::from_be_bytes([
                chunk[i * 4],
                chunk[i * 4 + 1],
                chunk[i * 4 + 2],
                chunk[i * 4 + 3],
            ]);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let (mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh) =
            (h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
        for i in 0..64 {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ ((!e) & g);
            let t1 = hh
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K[i])
                .wrapping_add(w[i]);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            hh = g;
            g = f;
            f = e;
            e = d.wrapping_add(t1);
            d = c;
            c = b;
            b = a;
            a = t1.wrapping_add(t2);
        }
        h[0] = h[0].wrapping_add(a);
        h[1] = h[1].wrapping_add(b);
        h[2] = h[2].wrapping_add(c);
        h[3] = h[3].wrapping_add(d);
        h[4] = h[4].wrapping_add(e);
        h[5] = h[5].wrapping_add(f);
        h[6] = h[6].wrapping_add(g);
        h[7] = h[7].wrapping_add(hh);
    }
    h.iter().map(|x| format!("{x:08x}")).collect()
}

